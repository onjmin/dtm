/**
 * ライブラリのバージョン。**書き出したファイルに埋め込むための唯一の出どころ。**
 *
 * ## 何のためにあるか
 *
 * 自動作曲が使う素材（`compose-phrases.ts` など）は外部のコーパスから作る。
 * そのコーパスに「パブリックドメインとして投稿されたが実はそうでなかった」ものが
 * 混じっていた場合、**どのバージョンまでが汚染されているか**を後から言えなければ、
 * 是正のしようがない（全部を疑うか、何もしないかの二択になる）。
 *
 * だから書き出す MML と MIDI にバージョンを埋める。手元のファイルを見れば、
 * それがどの素材から作られたかを {@link file://../docs/dataset-provenance.md} で
 * 引ける。素材を差し替えたらバージョンを上げ、台帳に追記する。
 *
 * ## package.json と二重管理になる理由
 *
 * ブラウザ向けのバンドルに `package.json` を読ませたくないので定数で持つ。
 * ずれると埋め込む値が嘘になるので、`scripts/check-version.ts` が一致を検算する。
 */
